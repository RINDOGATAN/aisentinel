/**
 * The words of the four register PDFs (AI system register, assessment
 * portfolio, model inventory, compliance summary) and of the audit-trail CSV,
 * in English and Spanish.
 *
 * English is exactly what those files printed before they had a language; a
 * test holds it there. Spanish uses the terms of the screens (the `common`
 * namespace of src/i18n/messages/es.json) and of the Spanish text of
 * Regulation (EU) 2024/1689 (proveedor, responsable del despliegue).
 *
 * Enum values print as stored, de-snaked, in English; in Spanish they print
 * as the screens name them, and an unknown value falls back to the English
 * form rather than disappearing.
 *
 * Pure module: no Prisma, no React, no Next.
 */

import { readLocale } from "@/lib/locale-cookie";

export type PdfLocale = "en" | "es";

/**
 * ?locale= wins; otherwise the `locale` cookie the screens use (read from the
 * Cookie header the way next-intl reads it); otherwise English.
 */
export function exportLocale(param: string | null | undefined, cookieHeader: string | null | undefined): PdfLocale {
  if (param === "es" || param === "en") return param;
  return readLocale(cookieHeader);
}

