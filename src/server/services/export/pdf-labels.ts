function label(map: Record<string, string>, key: string, locale: PdfLocale): string {
  return locale === "es" ? (map[key] ?? deSnake(key)) : deSnake(key);
}

/** Lifecycle, assessment and compliance statuses. */
export const statusLabel = (key: string, locale: PdfLocale) => label(STATUS_ES, key, locale);
/** EU AI Act risk tiers; English prints the stored value unchanged. */
export const riskLabel = (key: string, locale: PdfLocale) => (locale === "es" ? (RISK_ES[key] ?? deSnake(key)) : key);
export const techniqueLabel = (key: string, locale: PdfLocale) => label(TECHNIQUE_ES, key, locale);
/** The organisation's role; English prints the stored value unchanged. */
export const roleLabel = (key: string, locale: PdfLocale) => (locale === "es" ? (ROLE_ES[key] ?? deSnake(key)) : key);
export const assessmentTypeLabel = (key: string, locale: PdfLocale) => label(ASSESSMENT_TYPE_ES, key, locale);

